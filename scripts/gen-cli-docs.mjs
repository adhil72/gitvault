// Generates docs/cli.md from `gitvault commands --json` (single source: the clap definitions).
import { execFileSync } from 'node:child_process'
import { mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const bin = join(root, 'target', 'debug', 'gitvault')
const home = mkdtempSync(join(tmpdir(), 'gitvault-docs-'))
const tree = JSON.parse(
  execFileSync(bin, ['commands', '--json'], {
    env: { ...process.env, GITVAULT_HOME: home },
  }).toString(),
)

const out = [
  '# GitVault CLI reference',
  '',
  '> Generated by `pnpm gen:docs` from the command definitions. Do not edit by hand.',
  '',
]
const walk = (node, path) => {
  const name = [...path, node.name].join(' ')
  out.push(`${'#'.repeat(Math.min(path.length + 2, 5))} \`${name}\``, '')
  if (node.about) out.push(node.about, '')
  for (const arg of node.args ?? []) {
    const flag = arg.long ? `--${arg.long}` : `<${arg.name}>`
    out.push(`- \`${flag}\`${arg.required ? ' (required)' : ''}${arg.help ? `: ${arg.help}` : ''}`)
  }
  if (node.args?.length) out.push('')
  for (const child of node.subcommands ?? []) walk(child, [...path, node.name])
}
walk(tree, [])
writeFileSync(join(root, 'docs', 'cli.md'), `${out.join('\n')}\n`)
console.log('wrote docs/cli.md')
